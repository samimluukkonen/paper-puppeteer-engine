import { readFile } from 'node:fs/promises';
import { expect } from '@playwright/test';
import { rigFileSchema, skinFileSchema } from '../../src/engine/schemas.js';
import { test, inspectorControl } from './fixtures.js';

test('visual attachments and partial skins round trip with history and alignment selection', async ({ page }) => {
  test.setTimeout(120_000);
  await page.goto('rig-editor/');
  await expect(page.locator('#validation')).toHaveText('Validation: OK');
  const panel = page.locator('#attachment-panel');
  await inspectorControl(page, '#attachment-panel select');
  const downloadRig = async () => {
    const waiting = page.waitForEvent('download');
    await page.locator('#download-json').click();
    const download = await waiting;
    return rigFileSchema.parse(JSON.parse(await readFile(await download.path(), 'utf8')));
  };
  const original = await downloadRig();
  await panel.getByLabel('Attachment slot', { exact: true }).selectOption('rightHandVisual');
  await expect(page.locator('#inspector')).toContainText('rightHandVisual');
  await panel.getByLabel('Skin name', { exact: true }).fill('artist-alternate');
  await panel.getByRole('button', { name: 'Create skin', exact: true }).click();
  await expect(panel.getByLabel('Active skin', { exact: true })).toHaveValue('artist-alternate');
  await panel.getByLabel('Assigned attachment', { exact: true }).selectOption('rightHandGrip');
  await expect(page.locator('#inspector')).toContainText('rightHandGrip');
  await panel.getByRole('button', { name: 'Clear assignment', exact: true }).click();
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('');
  await page.locator('#undo').click();
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('rightHandGrip');
  await page.locator('#redo').click();
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('');
  await panel.getByRole('button', { name: 'Remove override', exact: true }).click();
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('rightHandDefault');
  await panel.getByLabel('Attachment ID', { exact: true }).fill('artist-hand');
  await panel.getByLabel('Attachment artwork', { exact: true }).selectOption('paper-right-grip-hand');
  await panel.getByRole('button', { name: 'Create attachment', exact: true }).click();
  await panel.getByLabel('Assigned attachment', { exact: true }).selectOption('artist-hand');
  await expect(page.locator('#inspector')).toContainText('artist-hand');
  await page.locator('#rig-preview-pose').selectOption('walk');
  await page.locator('#rig-preview-time').fill('450');
  await page.locator('#rig-preview-time').dispatchEvent('change');
  const canvas = page.locator('#editor-stage canvas');
  const custom = await canvas.screenshot();
  await panel.getByLabel('Active skin', { exact: true }).selectOption('default');
  expect((await canvas.screenshot()).equals(custom)).toBe(false);
  await panel.getByLabel('Active skin', { exact: true }).selectOption('artist-alternate');
  expect((await canvas.screenshot()).equals(custom)).toBe(true);
  await expect(page.locator('#rig-preview-time')).toHaveValue('450');
  await panel.getByLabel('Attachment slot', { exact: true }).selectOption('headVisual');
  await panel.getByLabel('Assigned attachment', { exact: true }).selectOption('headArmored');
  const exported = await downloadRig();
  expect(exported.bones).toEqual(original.bones);
  expect(exported.ik).toEqual(original.ik);
  expect(exported.slots).toEqual(original.slots);
  expect(exported.attachments!.find((entry) => entry.id === 'artist-hand')!.texture).toBe('paper-right-grip-hand');
  expect(exported.skins).toEqual([
    { version: 1, name: 'artist-alternate', slots: { rightHandVisual: 'artist-hand', headVisual: 'headArmored' } },
  ]);
  await page.locator('#rig-tools-open').click();
  await page.locator('#reload-exported').click();
  await page.locator('#rig-tools-dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await panel.getByLabel('Active skin', { exact: true }).selectOption('artist-alternate');
  await panel.getByLabel('Attachment slot', { exact: true }).selectOption('rightHandVisual');
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('artist-hand');
  await expect(page.locator('#validation')).toHaveText('Validation: OK');
  await panel.getByLabel('Active skin', { exact: true }).selectOption('default');
  await panel.getByLabel('Assigned attachment', { exact: true }).selectOption('rightHandGrip');
  const waiting = page.waitForEvent('download');
  await panel.getByRole('button', { name: 'Download skin JSON', exact: true }).click();
  const skinDownload = await waiting;
  const skin = skinFileSchema.parse(JSON.parse(await readFile(await skinDownload.path(), 'utf8')));
  expect(skin.slots.rightHandVisual).toBe('rightHandGrip');
  expect(skinDownload.suggestedFilename()).toBe('default.json');
  await expect(page.locator('#dirty-status')).toHaveText('No changes');
});

test('skin switching during animation and rig authoring preserve animation JSON and playhead', async ({ page }) => {
  await page.goto('animation-editor/');
  await expect(page.locator('#animation-status')).toHaveText('Validation: OK');
  const panel = page.locator('#attachment-panel');
  await inspectorControl(page, '#attachment-panel select');
  const exportAnimation = async () => {
    const waiting = page.waitForEvent('download');
    await page.locator('#animation-download').click();
    const download = await waiting;
    return readFile(await download.path(), 'utf8');
  };
  const original = await exportAnimation();
  await page.locator('#play-pause').click();
  await panel.getByLabel('Active skin', { exact: true }).selectOption('helmet-only');
  const held = await page.locator('#timeline-time-input').inputValue();
  await expect.poll(() => page.locator('#timeline-time-input').inputValue()).not.toBe(held);
  await panel.getByLabel('Active skin', { exact: true }).selectOption('default');
  await page.getByRole('combobox', { name: 'Editor Mode', exact: true }).selectOption('rig-tweak');
  const paused = await page.locator('#timeline-time-input').inputValue();
  await panel.getByLabel('Attachment slot', { exact: true }).selectOption('rightHandVisual');
  await panel.getByLabel('Skin name', { exact: true }).fill('animation-outfit');
  await panel.getByRole('button', { name: 'Create skin', exact: true }).click();
  await panel.getByLabel('Assigned attachment', { exact: true }).selectOption('rightHandGrip');
  await (await inspectorControl(page, '#tweak-undo')).click();
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('rightHandDefault');
  await (await inspectorControl(page, '#tweak-redo')).click();
  await expect(panel.getByLabel('Assigned attachment', { exact: true })).toHaveValue('rightHandGrip');
  await expect(page.locator('#timeline-time-input')).toHaveValue(paused);
  await page.getByRole('combobox', { name: 'Editor Mode', exact: true }).selectOption('animation');
  expect(await exportAnimation()).toBe(original);
});

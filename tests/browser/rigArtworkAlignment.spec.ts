import { expect } from '@playwright/test';
import { rigFileAction, test } from './fixtures.js';

test('replacement forearm alignment, pose inspection, facing and export reload preserve placement', async ({
  page,
}) => {
  await page.goto('rig-editor/');
  await expect(page.locator('#validation')).toHaveText('Validation: OK');
  await page.getByRole('treeitem', { name: '◇ leftForearmVisual', exact: true }).click();
  const inspector = page.locator('#inspector');
  const originPx = inspector.locator('input[data-field="originX"][data-pixels]');
  const origin = inspector.locator('input[data-scope="attachment"][data-field="originX"]:not([data-pixels])');
  const offset = inspector.locator('input[data-scope="attachment"][data-field="x"]');
  const slotX = inspector.locator('input[data-scope="slot"][data-field="x"]');
  const boneRotation = page.locator('#inspector input[data-scope="bone"][data-field="rotation"]');
  const originalSlot = await slotX.inputValue();
  const panel = page.locator('#artwork-panel');
  await panel.locator('summary').click();
  await panel.getByLabel('Artwork asset', { exact: true }).selectOption('paper-left-forearm');
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 137;
    canvas.height = 251;
    const context = canvas.getContext('2d')!;
    context.fillStyle = '#ff00ff';
    context.fillRect(0, 0, 137, 251);
    return canvas.toDataURL().split(',')[1]!;
  });
  await panel
    .getByLabel('Import sprite')
    .setInputFiles({ name: 'alignment.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await panel.getByRole('button', { name: 'Preview Replacement', exact: true }).click();
  await expect(inspector.locator('[data-alignment="dimensions"]')).toHaveText('137 × 251');
  await panel.getByRole('button', { name: 'Apply Replacement', exact: true }).click();
  await page.locator('#edit-mode').selectOption('sprite');
  const joint = (await inspector.locator('[data-alignment="joint"]').textContent())!.split(',').map(Number);
  const bounds = await page.locator('#editor-stage canvas').boundingBox();
  if (!bounds) throw new Error('Missing editor canvas');
  const start = { x: bounds.x + (joint[0]! / 760) * bounds.width, y: bounds.y + (joint[1]! / 640) * bounds.height };
  const initialOffset = await offset.inputValue();
  await page.mouse.move(start.x, start.y);
  await page.mouse.down();
  await page.mouse.move(start.x + 20, start.y + 10, { steps: 4 });
  await expect(offset).toHaveValue(initialOffset);
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await expect(offset).toHaveValue(initialOffset);
  await page.mouse.move(start.x, start.y);
  await page.mouse.down();
  await page.mouse.move(start.x + 20, start.y + 10, { steps: 4 });
  await page.mouse.up();
  await expect(offset).not.toHaveValue(initialOffset);
  await page.locator('#undo').click();
  await expect(offset).toHaveValue(initialOffset);
  await page.locator('#redo').click();
  await expect(offset).not.toHaveValue(initialOffset);
  const draggedOffset = await offset.inputValue();
  await inspector.getByRole('button', { name: 'Reset sprite offset', exact: true }).click();
  await expect(offset).toHaveValue('0');
  await page.locator('#undo').click();
  await expect(offset).toHaveValue(draggedOffset);
  await offset.fill('12.123456789');
  await originPx.fill('13.123456789');
  await page.locator('#rig-mode-hint').click();
  await expect.poll(async () => Number(await origin.inputValue())).toBe(13.123456789 / 137);
  await inspector.getByRole('button', { name: 'Reset origin', exact: true }).click();
  await expect(originPx).toHaveValue('68.5');
  await page.locator('#undo').click();
  await expect(originPx).toHaveValue('13.123456789');
  await inspector.getByRole('button', { name: 'Center sprite origin', exact: true }).click();
  await expect(originPx).toHaveValue('68.5');
  await page.locator('#undo').click();
  await expect(originPx).toHaveValue('13.123456789');
  await expect(slotX).toHaveValue(originalSlot);
  // A selected joint reference remains visible with neighboring bones hidden.
  await page.locator('input[data-visibility="bones"]').uncheck();
  await page.locator('#dim-selection').check();
  await page.locator('#grid-snap').selectOption('1');
  await page.locator('#rig-mode-hint').click();
  await page.keyboard.press('ArrowRight');
  await expect(offset).toHaveValue('13');
  await page.locator('#undo').click();
  await expect(offset).toHaveValue('12.123456789');
  await page.locator('#redo').click();
  await expect(offset).toHaveValue('13');
  await page.locator('#rig-facing').selectOption('left');
  await page.locator('#rig-preview-pose').selectOption('walk');
  await page.locator('#rig-preview-time').fill('500');
  await expect(slotX).toBeDisabled();
  await page.locator('#rig-preview-pose').selectOption('');
  await page.getByRole('treeitem', { name: 'leftForearm', exact: true }).click();
  await boneRotation.fill('0.4');
  await page.locator('#rig-mode-hint').click();
  await page.locator('#undo').click();
  await page.locator('#redo').click();
  await page.getByRole('treeitem', { name: '◇ leftForearmVisual', exact: true }).click();
  await page.locator('#rig-facing').selectOption('right');
  // Reset presentation controls so the reload screenshot compares identical views.
  await page.locator('#edit-mode').selectOption('joint');
  await page.locator('#dim-selection').uncheck();
  await page.locator('#grid-snap').selectOption('0');
  await page.locator('input[data-visibility="bones"]').check();
  const canvas = page.locator('#editor-stage canvas');
  const before = await canvas.screenshot({ path: test.info().outputPath('aligned-forearm.png') });
  const download = page.waitForEvent('download');
  await page.locator('#download-json').click();
  expect((await download).suggestedFilename()).toBe('rig.json');
  await rigFileAction(page, '#reload-exported', (control) => control.click());
  await page.getByRole('treeitem', { name: '◇ leftForearmVisual', exact: true }).click();
  await expect(originPx).toHaveValue('13.123456789');
  await expect(offset).toHaveValue('13');
  expect((await canvas.screenshot()).equals(before)).toBe(true);
  await expect(page.locator('#validation')).toHaveText('Validation: OK');
});

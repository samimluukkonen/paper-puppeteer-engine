/** Returns focus to the Tools menu button, where the authoring tool panels were opened from. */
export function focusAuthoringToolsMenu(root: ParentNode = document, options?: FocusOptions): void {
  const menu = requireElement(root, ANIMATION_IDS.authoringTools, HTMLDetailsElement);
  const summary = menu.querySelector<HTMLElement>(':scope > summary');
  if (!summary) throw new Error(`Missing editor element #${ANIMATION_IDS.authoringTools} > summary`);
  summary.focus(options);
}
